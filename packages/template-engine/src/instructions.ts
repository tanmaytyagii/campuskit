/**
 * Setup instructions for a generated project.
 *
 * The same `SetupGuide` object is rendered in two places: on screen right
 * after a ZIP is generated, and as GETTING_STARTED.md inside the ZIP, so the
 * student always sees identical steps.
 */
import { escapeMarkdown } from './escape.ts';

export type CommandPlatform = 'all' | 'windows' | 'macos-linux';

export interface SetupCommand {
  command: string;
  platform: CommandPlatform;
  /** Optional short explanation shown next to the command. */
  label?: string | undefined;
}

export interface SetupStep {
  title: string;
  commands: SetupCommand[];
  note?: string | undefined;
}

export interface SetupPrerequisite {
  name: string;
  version?: string | undefined;
  url?: string | undefined;
  note?: string | undefined;
}

export interface SetupGuide {
  projectName: string;
  folderName: string;
  templateId: string;
  templateName: string;
  templateVersion: string;
  generatedOn: string;
  prerequisites: SetupPrerequisite[];
  steps: SetupStep[];
  notes: string[];
  choices: Array<{ label: string; value: string }>;
}

const PLATFORM_LABEL: Record<CommandPlatform, string> = {
  all: '',
  windows: 'Windows (PowerShell)',
  'macos-linux': 'macOS / Linux',
};

function renderCommands(commands: SetupCommand[]): string {
  const groups = new Map<CommandPlatform, SetupCommand[]>();
  for (const command of commands) {
    const list = groups.get(command.platform) ?? [];
    list.push(command);
    groups.set(command.platform, list);
  }
  const blocks: string[] = [];
  for (const [platform, list] of groups) {
    const heading = PLATFORM_LABEL[platform];
    const language = platform === 'windows' ? 'powershell' : 'bash';
    const body = list.map((item) => item.command).join('\n');
    blocks.push(`${heading ? `${heading}:\n\n` : ''}\`\`\`${language}\n${body}\n\`\`\``);
  }
  return blocks.join('\n\n');
}

/**
 * Renders GETTING_STARTED.md. Text written by template authors (step titles,
 * notes) is trusted Markdown; values typed by the student (the project name
 * and option values) are escaped so they always render literally.
 */
export function renderGettingStarted(guide: SetupGuide): string {
  const lines: string[] = [];
  lines.push(`# Getting started with ${escapeMarkdown(guide.projectName)}`);
  lines.push('');
  lines.push(
    `This project was generated by CampusKit from the **${guide.templateName}** template ` +
      `(\`${guide.templateId}\`, version ${guide.templateVersion}) on ${guide.generatedOn}.`,
  );
  lines.push('');

  lines.push('## Before you start');
  lines.push('');
  for (const prerequisite of guide.prerequisites) {
    let line = `- **${prerequisite.name}${prerequisite.version ? ` ${prerequisite.version}` : ''}**`;
    if (prerequisite.url) line += ` (<${prerequisite.url}>)`;
    if (prerequisite.note) line += `: ${prerequisite.note}`;
    lines.push(line);
  }
  lines.push('');

  lines.push('## Steps');
  lines.push('');
  guide.steps.forEach((step, index) => {
    lines.push(`### ${index + 1}. ${step.title}`);
    lines.push('');
    if (step.commands.length > 0) {
      lines.push(renderCommands(step.commands));
      lines.push('');
    }
    if (step.note) {
      lines.push(step.note);
      lines.push('');
    }
  });

  if (guide.choices.length > 0) {
    lines.push('## Your customization');
    lines.push('');
    lines.push('| Setting | Value |');
    lines.push('| --- | --- |');
    for (const choice of guide.choices) {
      lines.push(`| ${choice.label} | ${escapeMarkdown(choice.value) || '_(left empty)_'} |`);
    }
    lines.push('');
  }

  if (guide.notes.length > 0) {
    lines.push('## Good to know');
    lines.push('');
    for (const note of guide.notes) lines.push(`- ${note}`);
    lines.push('');
  }

  lines.push('## Using a template honestly');
  lines.push('');
  lines.push(
    'This code is a starting point. If you submit it for coursework, follow your institution’s rules, ' +
      'say that you started from a CampusKit template, and make sure you can explain every part you present. ' +
      'The README and docs/ folder explain how the project works.',
  );
  lines.push('');
  return lines.join('\n');
}
